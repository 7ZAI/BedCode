/**
 * 终端可滚动历史行数上限（xterm 渲染侧 buffer）
 *
 * 与后端 channels.global_queue_capacity（默认 50000 事件）有意解耦：
 * 后端事件粒度 = 单次 PTY 读取（常为几个字节：一次按键回显、一行输出片段），
 * 一个事件往往不足一行，故 50000 事件展开后远少于 50000 可见行，解耦无丢失风险。
 * 后端历史队列保留 50000 个输出事件，主要为晚加入的移动端提供深回放；
 * 桌面端作为渲染源头，xterm 只保留浅层 10000 行渲染缓冲以控制内存与渲染开销
 * （深历史由后端队列持有，移动端按需回放，不在桌面端常驻展开）。
 * "最早输出被截断"提示由后端 min_seq > 0 驱动，队列放宽到 50000 后触发更晚、
 * 更不易打扰；桌面端向上滚动最多只能回溯 10000 行属本设计的预期行为。
 */
export const TERMINAL_SCROLLBACK = 10000
